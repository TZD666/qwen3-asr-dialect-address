import csv
import re

RAW = Path(__file__).resolve().parent.parent / "data" / "addresses" / "raw" / "adcodes.csv"

# 泛名区县：不生成别名（"东区"→"东" 会在任何文本里命中），并压低先验
_GENERIC_DISTRICT = {"东区", "西区", "南区", "北区", "中区", "新区", "郊区", "城区", "矿区", "市区",
                     "市辖区", "县", "省直辖县级行政区划", "自治区直辖县级行政区划"}
_ETHNIC_INFIX = re.compile(r"^(.{2,}?)(?:[一-鿿]{1,4}族)?(?:自治区|自治州|自治县|自治旗)$")


def _aliases_for(name: str) -> tuple[str, ...]:
    """行政区名 → 口语简称。只产生 ≥2 字的别名，1 字别名到处乱命中。"""
    out: set[str] = set()
    m = _ETHNIC_INFIX.match(name)
    if m:
        out.add(m.group(1))                       # 宁夏回族自治区 → 宁夏；延边朝鲜族自治州 → 延边
    for suf in ("特别行政区", "地区", "林区", "新区", "省", "市", "区", "县", "盟", "旗"):
        if name.endswith(suf) and len(name) - len(suf) >= 2:
            out.add(name[: -len(suf)])
            break
    return tuple(sorted(a for a in out if len(a) >= 2 and a != name))


def load_national() -> None:
    if not RAW.exists():
        print(f"（未找到 {RAW.name}，跳过全国表）")
        return
    have = {e["adcode"] for e in entries}
    rows = []
    with RAW.open(encoding="utf-8") as f:
        for r in csv.DictReader(f):
            code12 = r["adcode"].strip()
            name = r["name"].strip()
            if len(code12) < 6 or not name or name in _GENERIC_DISTRICT:
                continue
            code = code12[:6]
            if code.endswith("0000"):
                level, parent = "province", None
            elif code.endswith("00"):
                level, parent = "city", code[:2] + "0000"
            else:
                level = "district"
                city = code[:4] + "00"
                parent = city  # 直辖市/省直辖县的市级节点可能不存在，稍后回退到省
            try:
                lng, lat = float(r["longitude"]), float(r["latitude"])
            except (TypeError, ValueError):
                lng = lat = None
            rows.append((code, name, level, parent, lng, lat))

    codes = {c for c, *_ in rows} | have
    added = 0
    for code, name, level, parent, lng, lat in rows:
        if code in have:
            continue
        if parent and parent not in codes:
            parent = code[:2] + "0000"            # 市级节点缺失 → 挂到省
        generic = name in _GENERIC_DISTRICT or len(name) <= 2
        entries.append({
            "name": name, "level": level, "adcode": code, "parent": parent,
            "aliases": [] if generic else list(_aliases_for(name)),
            "prior": 0.3 if generic else 0.5,
            "lng": lng, "lat": lat,
        })
        added += 1
    print(f"全国表补入 {added} 条（省市区）")


