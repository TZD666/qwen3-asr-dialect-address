entries: list[dict] = []


def add(name, level, adcode, parent=None, aliases=(), prior=0.5):
    entries.append(
        {
            "name": name,
            "level": level,
            "adcode": adcode,
            "parent": parent,
            "aliases": list(aliases),
            "prior": prior,
        }
    )


def roads(parent_adcode: str, items: list[tuple[str, float] | tuple[str, float, tuple]]):
    """批量加道路/地标。items: [(名, 先验) 或 (名, 先验, 别名元组)]"""
    for i, it in enumerate(items, 1):
        name, prior = it[0], it[1]
        aliases = it[2] if len(it) > 2 else ()
        # 自动补一个去掉后缀的别名：xx街道→xx（口语常省略后缀）。
        # 只保留 ≥3 字的：2 字别名（人民广场→人民、中山路→中山、北京路→北京）在全国表里
        # 必然撞上别的城市/区县，害大于利。需要的 2 字别名用 items 里显式给。
        auto = set(aliases)
        for suf in ("街道", "步行街", "古镇", "国际机场", "广场", "大道", "路", "街"):
            if name.endswith(suf) and len(name) - len(suf) >= 3:
                auto.add(name[: -len(suf)])
                break
        add(name, "road", f"{parent_adcode}-{i:02d}", parent_adcode, tuple(sorted(auto)), prior)


